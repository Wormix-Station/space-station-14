using System.Linq;
using Content.Shared._Wormix.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Wormix.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class BanPresetWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<BanPresetPrototype>? PresetChosen;

    public BanPresetWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        foreach (var preset in _prototypes.EnumeratePrototypes<BanPresetPrototype>().OrderBy(preset => preset.Name))
        {
            var button = new Button
            {
                Text = preset.Name,
                HorizontalExpand = true,
            };
            button.OnPressed += _ =>
            {
                PresetChosen?.Invoke(preset);
                Close();
            };
            PresetList.AddChild(button);
        }
    }
}
