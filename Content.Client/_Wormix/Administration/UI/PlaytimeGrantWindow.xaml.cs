using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Wormix.Administration;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Wormix.Administration.UI;

[GenerateTypedNameReferences]
public sealed partial class PlaytimeGrantWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    private sealed record JobRow(string Tracker, string Title, BoxContainer Row, LineEdit Minutes, CheckBox Pick);

    private readonly List<JobRow> _rows = new();

    public event Action<string, PlaytimeGrantMode, int?, List<PlaytimeGrantEntry>>? Submitted;

    public PlaytimeGrantWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PopulateJobs();
        OverallInput.IsValid = ValidMinutes;
        GroupInput.IsValid = ValidMinutes;
        GroupToggle.OnToggled += args => ShowGroupMode(args.Pressed);
        SearchInput.OnTextChanged += args => ApplyFilter(args.Text);
        AddButton.OnPressed += _ => Submit(PlaytimeGrantMode.Add);
        SetButton.OnPressed += _ => Submit(PlaytimeGrantMode.Set);
    }

    private void PopulateJobs()
    {
        // Several jobs can share one playtime tracker; show each tracker once.
        var used = new HashSet<string>();

        foreach (var job in _prototypes.EnumeratePrototypes<JobPrototype>().OrderBy(job => job.LocalizedName))
        {
            var tracker = job.PlayTimeTracker.ToString();
            if (!used.Add(tracker))
                continue;

            var minutes = new LineEdit
            {
                MinSize = new Vector2(100, 0),
                PlaceHolder = "0",
                IsValid = ValidMinutes,
            };
            var pick = new CheckBox { Visible = false };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };
            row.AddChild(new TextureRect
            {
                Texture = _entityManager.System<SpriteSystem>().Frame0(_prototypes.Index(job.Icon).Icon),
                MinSize = new Vector2(24, 24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            });
            row.AddChild(new Label
            {
                Text = job.LocalizedName,
                HorizontalExpand = true,
                ClipText = true,
            });
            row.AddChild(minutes);
            row.AddChild(pick);
            JobList.AddChild(row);

            _rows.Add(new JobRow(tracker, job.LocalizedName, row, minutes, pick));
        }
    }

    private void ApplyFilter(string query)
    {
        var text = query.Trim();

        foreach (var row in _rows)
        {
            row.Row.Visible = text.Length == 0 ||
                              row.Title.Contains(text, StringComparison.CurrentCultureIgnoreCase) ||
                              row.Tracker.Contains(text, StringComparison.OrdinalIgnoreCase);
        }
    }

    private void ShowGroupMode(bool grouped)
    {
        GroupInput.Visible = grouped;

        foreach (var row in _rows)
        {
            row.Minutes.Visible = !grouped;
            row.Pick.Visible = grouped;
        }
    }

    private void Submit(PlaytimeGrantMode mode)
    {
        int? overall = int.TryParse(OverallInput.Text, out var parsed) ? parsed : null;
        var entries = new List<PlaytimeGrantEntry>();

        if (GroupToggle.Pressed && int.TryParse(GroupInput.Text, out var groupMinutes))
        {
            entries.AddRange(_rows
                .Where(row => row.Pick.Pressed)
                .Select(row => new PlaytimeGrantEntry(row.Tracker, groupMinutes)));
        }
        else
        {
            entries.AddRange(_rows
                .Where(row => int.TryParse(row.Minutes.Text, out _))
                .Select(row => new PlaytimeGrantEntry(row.Tracker, int.Parse(row.Minutes.Text))));
        }

        Submitted?.Invoke(CkeyInput.Text.Trim(), mode, overall, entries);
    }

    public void SetStatus(string? text, bool success)
    {
        StatusLabel.Visible = !string.IsNullOrEmpty(text);
        StatusLabel.Text = text ?? string.Empty;
        StatusLabel.FontColorOverride = success ? Color.LightGreen : Color.OrangeRed;

        if (!success)
            return;

        OverallInput.Text = string.Empty;
        GroupInput.Text = string.Empty;

        foreach (var row in _rows)
        {
            row.Minutes.Text = string.Empty;
            row.Pick.Pressed = false;
        }
    }

    private static bool ValidMinutes(string text)
    {
        return text.Length == 0
               || text == "-"
               || text.Length <= 7 && int.TryParse(text, out _);
    }
}
