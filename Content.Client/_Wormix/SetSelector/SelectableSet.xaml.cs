using Content.Shared._Wormix.SetSelector;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Wormix.SetSelector;

[GenerateTypedNameReferences]
public sealed partial class SelectableSet : Control
{
    [Dependency] private IPrototypeManager _proto = default!;

    public SelectableSet(SelectableSetInfo set, SpriteSystem spriteSystem)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Icon.Texture = spriteSystem.Frame0(set.Sprite);
        // SpriteComponent.Icon не учитывает цвет слоя, поэтому тонированные варианты
        // (полотенца, шорты, цветные комбинезоны и т.д.) выглядели одинаково. Накладываем цвет сами.
        if (set.Sprite is SpriteSpecifier.EntityPrototype { EntityPrototypeId: var entId } &&
            _proto.TryIndex<EntityPrototype>(entId, out var proto) &&
            proto.Components.TryGetValue("Sprite", out var spriteData) &&
            spriteData.Component is SpriteComponent { LayerData.Count: > 0 } spriteComp &&
            spriteComp.LayerData[0].Color is var layerColor && layerColor != Color.White)
        {
            Icon.ModulateSelfOverride = layerColor;
        }
        SetName.Text = Loc.GetString(set.Name);
        SetDescription.Text = Loc.GetString(set.Description);
        SetButton.Text = Loc.GetString(set.Selected ? "set-selector-button-deselect" : "set-selector-button-select");
        SetButton.ModulateSelfOverride = set.Selected ? new Color(40, 84, 35) : new Color(68, 75, 103);
    }
}
