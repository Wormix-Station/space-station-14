using System.Globalization;
using System.Linq;
using Content.Client._Wormix.Administration.UI;
using Content.Client.Decals.UI;
using Content.Shared.Administration;
using Content.Shared._Wormix.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Administration.UI
{
    // Wormix: extended announce panel - sender signature, custom color and sound, map targets.
    [GenerateTypedNameReferences]
    public sealed partial class AdminAnnounceWindow : DefaultWindow
    {
        [Dependency] private ILocalizationManager _loc = default!;

        private const string DefaultColorHex = "f0c040";
        private const int MaxSenderLength = 32;
        private const float MinVolume = 1f;
        private const float MaxVolume = 10f;
        private const float DefaultVolume = 5f;

        private AnnouncePresetWindow? _presetWindow;
        private PaletteColorPicker? _palette;

        public AdminAnnounceWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            Announcement.Placeholder = new Rope.Leaf(_loc.GetString("admin-announce-announcement-placeholder"));

            AnnounceMethod.AddItem(_loc.GetString("admin-announce-target-all"));
            AnnounceMethod.SetItemMetadata(0, AnnounceDestination.All);
            AnnounceMethod.AddItem(_loc.GetString("admin-announce-type-server"));
            AnnounceMethod.SetItemMetadata(1, AnnounceDestination.Server);
            AnnounceMethod.OnItemSelected += args => AnnounceMethod.SelectId(args.Id);

            Announcement.OnKeyBindUp += OnAnnouncementChanged;
            ColorInput.OnTextChanged += OnColorChanged;
            ColorSwatch.OnPressed += OnSwatchPressed;
            VolumeInput.OnTextChanged += OnVolumeChanged;
            SenderInput.OnTextChanged += OnSenderChanged;
            PresetsButton.OnPressed += OnPresetsPressed;

            UpdateSwatch();
        }

        public string AnnouncerText => Announcer.Text;
        public string SenderText => SenderInput.Text;
        public string AnnouncementText => Rope.Collapse(Announcement.TextRope);

        public AnnounceDestination Destination =>
            AnnounceMethod.SelectedMetadata is AnnounceDestination destination
                ? destination
                : AnnounceDestination.All;

        public string ColorHex
        {
            get
            {
                var text = ColorInput.Text.Trim().TrimStart('#');
                return text.Length is 3 or 6 ? text : DefaultColorHex;
            }
        }

        public string SoundPath => SoundInput.Text;
        public bool KeepOpen => KeepWindowOpen.Pressed;

        public float Volume
        {
            get
            {
                return float.TryParse(VolumeInput.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var volume)
                    ? Math.Clamp(volume, MinVolume, MaxVolume)
                    : DefaultVolume;
            }
        }

        /// <summary>
        /// Rebuilds the destination selector: all maps reported by the server, plus server-wide.
        /// </summary>
        public void SetTargets(IReadOnlyList<AnnounceTarget> targets)
        {
            var previous = Destination;
            var selectedId = 0;
            var index = 0;

            AnnounceMethod.Clear();

            AnnounceMethod.AddItem(_loc.GetString("admin-announce-target-all"));
            AnnounceMethod.SetItemMetadata(index++, AnnounceDestination.All);

            foreach (var target in targets)
            {
                AnnounceMethod.AddItem(target.Name);
                AnnounceMethod.SetItemMetadata(index, new AnnounceDestination(AdminAnnounceType.Map, target.Grid));

                if (previous.Type == AdminAnnounceType.Map && previous.Grid == target.Grid)
                    selectedId = index;

                index++;
            }

            AnnounceMethod.AddItem(_loc.GetString("admin-announce-type-server"));
            AnnounceMethod.SetItemMetadata(index, AnnounceDestination.Server);

            if (previous.Type == AdminAnnounceType.Server)
                selectedId = index;

            AnnounceMethod.SelectId(selectedId);
        }

        private void OnAnnouncementChanged(GUIBoundKeyEventArgs args)
        {
            AnnounceButton.Disabled = Rope.Collapse(Announcement.TextRope).TrimStart() == "";
        }

        private void OnColorChanged(LineEdit.LineEditEventArgs args)
        {
            var filtered = new string(args.Text.TrimStart('#').Where(Uri.IsHexDigit).ToArray());
            if (filtered.Length > 6)
                filtered = filtered[..6];

            if (ColorInput.Text != filtered)
                ColorInput.Text = filtered;

            UpdateSwatch();
        }

        private void UpdateSwatch()
        {
            Color.TryFromHex("#" + ColorHex, out var color);
            ColorSwatch.StyleBoxOverride = new StyleBoxFlat { BackgroundColor = color };
        }

        private void OnSwatchPressed(BaseButton.ButtonEventArgs args)
        {
            if (_palette == null)
            {
                _palette = new PaletteColorPicker();
                _palette.PaletteList.OnItemSelected += OnPalettePicked;
                _palette.OpenCenteredLeft();
                return;
            }

            if (_palette.IsOpen)
                _palette.Close();
            else
                _palette.Open();
        }

        private void OnPalettePicked(ItemList.ItemListSelectedEventArgs args)
        {
            if (args.ItemList.GetSelected().FirstOrDefault()?.Metadata is not Color color)
                return;

            ColorInput.Text = color.ToHexNoAlpha().TrimStart('#');
            UpdateSwatch();
        }

        private void OnVolumeChanged(LineEdit.LineEditEventArgs args)
        {
            if (float.TryParse(args.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var volume))
                VolumeInput.Text = Math.Clamp(volume, MinVolume, MaxVolume).ToString(CultureInfo.InvariantCulture);
        }

        private void OnSenderChanged(LineEdit.LineEditEventArgs args)
        {
            var text = new string(args.Text.Where(c => !char.IsControl(c)).ToArray());
            if (text.Length > MaxSenderLength)
                text = text[..MaxSenderLength];

            if (SenderInput.Text != text)
                SenderInput.Text = text;
        }

        private void OnPresetsPressed(BaseButton.ButtonEventArgs args)
        {
            if (_presetWindow is { Disposed: false })
            {
                _presetWindow.OpenCentered();
                return;
            }

            if (_presetWindow is { } old)
            {
                old.PresetChosen -= OnPresetChosen;
                _presetWindow = null;
            }

            _presetWindow = new AnnouncePresetWindow();
            _presetWindow.PresetChosen += OnPresetChosen;
            _presetWindow.OpenCentered();
        }

        private void OnPresetChosen(AnnouncePresetPrototype preset)
        {
            Announcement.TextRope = new Rope.Leaf(preset.Text);
            AnnounceButton.Disabled = string.IsNullOrWhiteSpace(preset.Text);
        }

        public override void Close()
        {
            _palette?.Close();
            _presetWindow?.Close();
            base.Close();
        }

        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                if (_presetWindow is { } preset)
                {
                    preset.PresetChosen -= OnPresetChosen;
                    if (!preset.Disposed)
                        preset.Dispose();
                }

                _presetWindow = null;
            }

            base.Dispose(disposing);
        }
    }
}
